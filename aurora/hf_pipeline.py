class AuroraTextEncoder(ModelMixin, ConfigMixin):
    """Small from-scratch text encoder: GQA transformer with 1D RoPE, SwiGLU and RMSNorm."""

    @register_to_config
    def __init__(
        self,
        vocab_size: int = 8192,
        dim: int = 384,
        depth: int = 6,
        heads: int = 6,
        kv_heads: int = 2,
        head_dim: int = 64,
        mlp_hidden: int = 1024,
        max_tokens: int = 64,
        pad_id: int = 0,
        bos_id: int = 2,
        eos_id: int = 3,
        null_id: int = 4,
        mask_id: int = 5,
    ):
        super().__init__()
        self.token_embedding = nn.Embedding(vocab_size, dim)
        self.blocks = nn.ModuleList([TextBlock(dim, heads, kv_heads, head_dim, mlp_hidden) for _ in range(depth)])
        self.norm = RMSNorm(dim)
        cos, sin = build_rope_1d(max_tokens, head_dim)
        self.register_buffer("rope_cos", cos, persistent=False)
        self.register_buffer("rope_sin", sin, persistent=False)

    def forward(self, ids: torch.Tensor):
        valid = ids.ne(self.config.pad_id)
        h = self.token_embedding(ids)
        for block in self.blocks:
            h = block(h, valid, self.rope_cos, self.rope_sin)
        return self.norm(h), valid


class AuroraLMTextEncoder(ModelMixin, ConfigMixin):
    """Frozen causal LM trunk -> RMSNorm (+ learned null prompt) -> bidirectional refiner blocks -> denoiser text tokens.
    Captions: [BOS] ids[:max_tokens-1] [PAD]...; the CFG null prompt is [NULL] [PAD]... (ids outside the LM vocab)."""

    @register_to_config
    def __init__(
        self,
        kind: str = "lm",
        vocab_size: int = 12288,
        lm_blocks: int = 18,  # LM blocks used (the trained run takes the stream before the last of 19)
        lm_dim: int = 768,
        lm_heads: int = 12,
        lm_ffn_mult: float = 2.8125,
        lm_norm_eps: float = 1e-6,
        lm_rope_theta: float = 100000.0,
        lm_value_residual: bool = True,
        lm_qk_norm: bool = True,
        dim: int = 768,
        depth: int = 2,
        heads: int = 12,
        kv_heads: int = 4,
        head_dim: int = 64,
        mlp_hidden: int = 2048,
        max_tokens: int = 96,
        bos_id: int = 12285,
        pad_id: int = 65535,
        null_id: int = 65534,
    ):
        super().__init__()
        self.lm = LMTrunk(vocab_size, lm_blocks, lm_dim, lm_heads, lm_ffn_mult, lm_norm_eps, lm_rope_theta,
                          lm_value_residual, lm_qk_norm)
        self.in_norm = RMSNorm(lm_dim)
        self.null = nn.Parameter(torch.zeros(1, 1, lm_dim))
        self.in_proj = nn.Linear(lm_dim, dim, bias=False) if dim != lm_dim else nn.Identity()
        self.blocks = nn.ModuleList([TextBlock(dim, heads, kv_heads, head_dim, mlp_hidden) for _ in range(depth)])
        self.norm = RMSNorm(dim)
        cos, sin = build_rope_1d(max_tokens, head_dim)
        self.register_buffer("rope_cos", cos, persistent=False)
        self.register_buffer("rope_sin", sin, persistent=False)

    def forward(self, ids: torch.Tensor):
        cfg = self.config
        valid = ids.ne(cfg.pad_id)
        is_null = ids[:, 0].eq(cfg.null_id)
        h = self.lm(ids.masked_fill(~valid | ids.eq(cfg.null_id), 0))  # causal + right padding: pads never seen
        h = self.in_norm(h)
        h = torch.where(is_null[:, None, None], self.null.to(h.dtype).expand_as(h), h)
        h = self.in_proj(h)
        for block in self.blocks:
            h = block(h, valid, self.rope_cos, self.rope_sin)
        return self.norm(h), valid


class AuroraDenoiser(ModelMixin, ConfigMixin):
    """Flow-matching DiT: velocity predictor on (B, 128, 16, 16) FLUX.2 latents, one latent pixel per token."""

    @register_to_config
    def __init__(
        self,
        latent_channels: int = 128,
        latent_size: int = 16,
        dim: int = 640,
        depth: int = 8,
        heads: int = 10,
        mlp_hidden: int = 1536,
        text_dim: int = 384,
        latent_layout: str = "flux2_pipeline",
    ):
        super().__init__()
        self.patch_in = nn.Linear(latent_channels, dim, bias=False)
        self.time_mlp = nn.Sequential(nn.Linear(256, dim), nn.SiLU(), nn.Linear(dim, dim))
        self.ada = nn.Linear(dim, 6 * dim)
        self.blocks = nn.ModuleList([DenoiserBlock(dim, heads, text_dim, mlp_hidden) for _ in range(depth)])
        self.norm = RMSNorm(dim)
        self.patch_out = nn.Linear(dim, latent_channels, bias=False)
        cos, sin = build_rope_2d(latent_size, dim // heads)
        self.register_buffer("rope_cos", cos, persistent=False)
        self.register_buffer("rope_sin", sin, persistent=False)

    def forward(self, z_t: torch.Tensor, t: torch.Tensor, text: torch.Tensor, text_valid: torch.Tensor):
        b, c, h, w = z_t.shape
        dim = self.config.dim
        x = self.patch_in(z_t.flatten(2).transpose(1, 2))
        t_emb = self.time_mlp(timestep_embedding(t, 256))
        t6 = self.ada(F.silu(t_emb)).view(b, 6, dim)
        for block in self.blocks:
            x = block(x, t6, text, text_valid, self.rope_cos, self.rope_sin)
        return self.patch_out(self.norm(x)).transpose(1, 2).reshape(b, c, h, w)


