"""AuroraIMG2-style text-to-image pipeline (load with trust_remote_code=True).

Based on the AuroraIMG2-50M-Preview pipeline (Apache-2.0), extended with a second text encoder type:
  * AuroraTextEncoder    -> the released from-scratch encoder (unchanged)
  * AuroraLMTextEncoder  -> a frozen pretrained causal LM (SlayerLab/Slayer149 GPT, Apache-2.0) + a small bidirectional
                            refiner; its LM weights are stored inside text_encoder/ so the repo is self-contained
Generated by trenowanie_generatora_obrazkow/export.py.

Components (all stored in the repo as separate sub-folders):
  * tokenizer     -> from-scratch byte-level BPE (8192 tokens), loaded with transformers
  * text_encoder  -> AuroraTextEncoder, ~12.7M params, trained from scratch (defined below)
  * transformer   -> AuroraDenoiser, ~50M params flow-matching DiT, trained from scratch (defined below)
  * vae           -> pretrained FLUX.2 small decoder (AutoencoderKLFlux2, Apache-2.0), frozen

Sampling is plain Euler on t = linspace(1, 0, steps + 1) with classifier-free guidance, i.e. exactly
what was used for the reported benchmark numbers.

NOTE: diffusers' custom-pipeline loader expects exactly ONE DiffusionPipeline subclass in this file.
"""
