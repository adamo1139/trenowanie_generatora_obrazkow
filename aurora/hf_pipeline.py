# Frozen-LM text encoder (GoLLeM / Slayer GPT, inference architecture, Apache-2.0)
# =============================================================================
class LMRMSNorm(nn.Module):
    def __init__(self, d, eps=1e-6):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(d))
        self.eps = eps

    def forward(self, x):
        return x * torch.rsqrt(x.float().pow(2).mean(-1, keepdim=True) + self.eps).to(x.dtype) * self.weight


def lm_apply_rope(x, base=100000.0):
    """Parameter-free RoPE on [B, H, T, D], interleaved convention (even/odd channel pairs)."""
    _, _, T, dim = x.shape
    pos = torch.arange(T, device=x.device, dtype=torch.float32)
    freq = 1.0 / (base ** (torch.arange(0, dim, 2, device=x.device, dtype=torch.float32) / dim))
    ang = torch.outer(pos, freq)
    cos, sin = ang.cos().to(x.dtype)[None, None], ang.sin().to(x.dtype)[None, None]
    even, odd = x[..., ::2], x[..., 1::2]
    return torch.stack((even * cos - odd * sin, even * sin + odd * cos), dim=-1).flatten(-2)


class LMSwiGLU(nn.Module):
    def __init__(self, d, hidden):
        super().__init__()
        self.gate = nn.Linear(d, hidden, bias=False)
        self.up = nn.Linear(d, hidden, bias=False)
        self.down = nn.Linear(hidden, d, bias=False)

    def forward(self, x):
        return self.down(F.silu(self.gate(x)) * self.up(x))


class LMBlock(nn.Module):
    def __init__(self, d, nh, ffn_mult, eps, rope_theta, value_residual, qk_norm, is_first=False):
        super().__init__()
        self.ln1, self.ln2 = LMRMSNorm(d, eps), LMRMSNorm(d, eps)
        self.qkv = nn.Linear(d, 3 * d)
        self.proj = nn.Linear(d, d)
        self.mlp = LMSwiGLU(d, int(round(ffn_mult * d)))
        self.nh, self.d, self.rope_theta = nh, d, rope_theta
        self.value_residual, self.qk_norm, self.is_first = value_residual, qk_norm, is_first
        if value_residual and not is_first:
            self.vr_lambda = nn.Parameter(torch.zeros(1))
        if qk_norm:
            self.q_norm, self.k_norm = LMRMSNorm(d // nh, eps), LMRMSNorm(d // nh, eps)

    def forward(self, x, v0=None):
        B, T, D = x.size()
        q, k, v = self.qkv(self.ln1(x)).split(self.d, dim=2)
        hd = D // self.nh
        q, k, v = (t.view(B, T, self.nh, hd).transpose(1, 2) for t in (q, k, v))
        if self.qk_norm:
            q, k = self.q_norm(q), self.k_norm(k)
        q, k = lm_apply_rope(q, self.rope_theta), lm_apply_rope(k, self.rope_theta)
        if self.value_residual:
            if self.is_first:
                v0 = v
            else:
                v = v + self.vr_lambda * v0
        y = F.scaled_dot_product_attention(q, k, v, is_causal=True)
        x = x + self.proj(y.transpose(1, 2).contiguous().view(B, T, D))
        return x + self.mlp(self.ln2(x)), v0


class LMTrunk(nn.Module):
    """Token embedding + the first n blocks of the LM (no final norm, no head)."""

    def __init__(self, vocab, n_blocks, d, nh, ffn_mult, eps, rope_theta, value_residual, qk_norm):
        super().__init__()
        self.tok = nn.Embedding(vocab, d)
        self.blocks = nn.ModuleList([LMBlock(d, nh, ffn_mult, eps, rope_theta, value_residual, qk_norm, i == 0)
                                     for i in range(n_blocks)])

    def forward(self, idx):
        x, v0 = self.tok(idx), None
        for b in self.blocks:
            x, v0 = b(x, v0)
        return x


# =============================================================================
# FLUX.2 latent packing layouts (used to turn the model's (128,16,16) latents into the decoder's input)
# =============================================================================
def _unpatchify_flux2(z):  # official FLUX.2 pipeline layout: channel = c*4 + dh*2 + dw
    b, c4, h, w = z.shape
    return z.reshape(b, c4 // 4, 2, 2, h, w).permute(0, 1, 4, 2, 5, 3).reshape(b, c4 // 4, h * 2, w * 2)


def _unpatchify_swap_subpixel(z):
    b, c4, h, w = z.shape
    return z.reshape(b, c4 // 4, 2, 2, h, w).permute(0, 1, 4, 3, 5, 2).reshape(b, c4 // 4, h * 2, w * 2)


def _unpatchify_subpixel_major(z):
    b, c4, h, w = z.shape
    return z.reshape(b, 2, 2, c4 // 4, h, w).permute(0, 3, 4, 1, 5, 2).reshape(b, c4 // 4, h * 2, w * 2)


def _unpatchify_subpixel_major_swapped(z):
    b, c4, h, w = z.shape
    return z.reshape(b, 2, 2, c4 // 4, h, w).permute(0, 3, 4, 2, 5, 1).reshape(b, c4 // 4, h * 2, w * 2)


UNPATCHIFY_LAYOUTS = {
    "flux2_pipeline": _unpatchify_flux2,
    "swap_subpixel": _unpatchify_swap_subpixel,
    "subpixel_major": _unpatchify_subpixel_major,
    "subpixel_major_swapped": _unpatchify_subpixel_major_swapped,
}


