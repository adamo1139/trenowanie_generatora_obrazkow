class AuroraIMG2Pipeline(DiffusionPipeline):
    """Text-to-image pipeline (256x256). Usage:

        pipe = DiffusionPipeline.from_pretrained(repo, custom_pipeline=repo, trust_remote_code=True)
        image = pipe("a red fox in the snow", num_inference_steps=50, guidance_scale=3.0).images[0]
    """

    def __init__(self, tokenizer, text_encoder, transformer, vae):
        super().__init__()
        self.register_modules(tokenizer=tokenizer, text_encoder=text_encoder, transformer=transformer, vae=vae)

    # ---- helpers -------------------------------------------------------------------------------
    def _autocast(self):
        device = self._execution_device
        if device.type == "cuda":
            dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
            return torch.autocast(device_type="cuda", dtype=dtype)
        return contextlib.nullcontext()

    def _is_lm(self) -> bool:
        return getattr(self.text_encoder.config, "kind", "") == "lm"

    def _tokenize(self, texts: List[str]) -> torch.Tensor:
        """[BOS] + BPE ids (max 62) + [EOS], padded with [PAD] to max_tokens. Same as in training."""
        cfg = self.text_encoder.config
        if self._is_lm():  # [BOS] ids[:max-1] [PAD]..., no leading space (prepare_data.py --encoder slayer149)
            cleaned = [" ".join(str(t).split()) for t in texts]
            encoded = self.tokenizer(cleaned, add_special_tokens=False)["input_ids"]
            rows = torch.full((len(cleaned), int(cfg.max_tokens)), int(cfg.pad_id), dtype=torch.long)
            for i, ids in enumerate(encoded):
                ids = list(ids)[: int(cfg.max_tokens) - 1]
                rows[i, 0] = int(cfg.bos_id)
                if ids:
                    rows[i, 1:1 + len(ids)] = torch.tensor(ids, dtype=torch.long)
            return rows
        max_len = int(cfg.max_tokens)
        cleaned = [" ".join(str(t).split()) for t in texts]
        # The training tokenizer uses ByteLevel(add_prefix_space=True), i.e. every caption was tokenised with a
        # leading space. The transformers wrapper can drop that setting when the tokenizer is saved/reloaded, so the
        # space is added explicitly here (a no-op if the backend already adds it).
        cleaned = [(" " + t) if t else t for t in cleaned]
        encoded = self.tokenizer(cleaned, add_special_tokens=False)["input_ids"]
        rows = torch.full((len(cleaned), max_len), int(cfg.pad_id), dtype=torch.long)
        for i, ids in enumerate(encoded):
            ids = list(ids)[: max_len - 2]
            rows[i, 0] = int(cfg.bos_id)
            if ids:
                rows[i, 1:1 + len(ids)] = torch.tensor(ids, dtype=torch.long)
            rows[i, 1 + len(ids)] = int(cfg.eos_id)
        return rows

    def _null_ids(self, batch: int) -> torch.Tensor:
        """The learned empty prompt used for classifier-free guidance: [BOS] [NULL] [EOS] [PAD]..."""
        cfg = self.text_encoder.config
        row = torch.full((int(cfg.max_tokens),), int(cfg.pad_id), dtype=torch.long)
        if self._is_lm():
            row[0] = int(cfg.null_id)
            return row[None, :].repeat(batch, 1)
        row[0], row[1], row[2] = int(cfg.bos_id), int(cfg.null_id), int(cfg.eos_id)
        return row[None, :].repeat(batch, 1)

    def encode_prompt(self, prompts: List[str], negative_prompts: Optional[List[str]], do_cfg: bool, device):
        ids = self._tokenize(prompts).to(device)
        with self._autocast():
            cond, cond_valid = self.text_encoder(ids)
            if not do_cfg:
                return cond, cond_valid
            if negative_prompts is None:
                uncond_ids = self._null_ids(len(prompts))
            else:
                uncond_ids = self._tokenize(negative_prompts)
            uncond, uncond_valid = self.text_encoder(uncond_ids.to(device))
        # unconditional first, conditional second (the order the model was evaluated with)
        return torch.cat([uncond, cond], dim=0), torch.cat([uncond_valid, cond_valid], dim=0)

    @torch.no_grad()
    def decode_latents(self, latents: torch.Tensor, chunk_size: int = 32) -> torch.Tensor:
        """Model latents (B,128,16,16) -> images in [-1, 1] via the FLUX.2 small decoder."""
        vae = self.vae
        eps = float(getattr(vae.config, "batch_norm_eps", 1e-4))
        mean = vae.bn.running_mean.detach().float().view(1, -1, 1, 1).to(latents.device)
        std = torch.sqrt(vae.bn.running_var.detach().float() + eps).view(1, -1, 1, 1).to(latents.device)
        unpatchify = UNPATCHIFY_LAYOUTS[self.transformer.config.latent_layout]
        outs = []
        for i in range(0, latents.shape[0], chunk_size):
            z = latents[i:i + chunk_size].float() * std + mean
            z = unpatchify(z)
            outs.append(vae.decode(z.to(vae.dtype)).sample.float().clamp(-1, 1))
        return torch.cat(outs, dim=0)

    # ---- main entry point ----------------------------------------------------------------------
    @torch.no_grad()
    def __call__(
        self,
        prompt: Union[str, List[str]],
        negative_prompt: Optional[Union[str, List[str]]] = None,
        num_inference_steps: int = 50,
        guidance_scale: float = 3.0,
        num_images_per_prompt: int = 1,
        generator: Optional[torch.Generator] = None,
        latents: Optional[torch.Tensor] = None,
        output_type: str = "pil",
        return_dict: bool = True,
    ):
        """
        Args:
            prompt: text prompt(s). English; prompts longer than 62 BPE tokens are truncated.
            negative_prompt: optional. None (default) uses the learned empty prompt the model was trained
                with for classifier-free guidance. Arbitrary negative prompts were not part of training.
            num_inference_steps: Euler steps. 50 = recommended (used for the benchmarks), 20 = fast.
            guidance_scale: classifier-free guidance scale. 3.0 recommended.
            output_type: "pil", "np", "pt" (tensor in [0,1]) or "latent" (raw model latents).
        """
        base = [prompt] if isinstance(prompt, str) else list(prompt)
        prompts = [p for p in base for _ in range(num_images_per_prompt)]
        negs = None
        if negative_prompt is not None:
            neg_base = [negative_prompt] * len(base) if isinstance(negative_prompt, str) else list(negative_prompt)
            if len(neg_base) != len(base):
                raise ValueError("negative_prompt must be a string or have the same length as prompt.")
            negs = [n for n in neg_base for _ in range(num_images_per_prompt)]

        device = self._execution_device
        b = len(prompts)
        do_cfg = guidance_scale != 1.0
        context, context_valid = self.encode_prompt(prompts, negs, do_cfg, device)

        tcfg = self.transformer.config
        shape = (b, tcfg.latent_channels, tcfg.latent_size, tcfg.latent_size)
        if latents is None:
            z = randn_tensor(shape, generator=generator, device=device, dtype=torch.float32)
        else:
            z = latents.to(device=device, dtype=torch.float32)

        ts = torch.linspace(1.0, 0.0, num_inference_steps + 1, device=device)
        for i in self.progress_bar(range(num_inference_steps)):
            t0, t1 = ts[i], ts[i + 1]
            with self._autocast():
                if do_cfg:
                    v = self.transformer(torch.cat([z, z], dim=0), t0.expand(2 * b), context, context_valid)
                    v_uncond, v_cond = v.chunk(2, dim=0)
                    velocity = v_uncond + guidance_scale * (v_cond - v_uncond)
                else:
                    velocity = self.transformer(z, t0.expand(b), context, context_valid)
            z = z + (t1 - t0) * velocity.float()

        if output_type == "latent":
            images = z
        else:
            img = (self.decode_latents(z) + 1.0) / 2.0
            if output_type == "pt":
                images = img
            else:
                arr = img.cpu().permute(0, 2, 3, 1).float().numpy()
                images = self.numpy_to_pil(arr) if output_type == "pil" else arr

        self.maybe_free_model_hooks()
        if not return_dict:
            return (images,)
        return ImagePipelineOutput(images=images)